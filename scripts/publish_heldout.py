"""Licence alignment + publish the held-out generations.

The three datasets contain text generated by Tiny Aya Global, which is CC-BY-NC-4.0, so the
datasets cannot be offered under a more permissive licence than the model that produced them.
Fixes the cards and uploads the held-out run.
"""
import re
from pathlib import Path

from huggingface_hub import HfApi, hf_hub_download

api = HfApi()
NS = "harishkotra"
NOTE = ("- licence: **CC-BY-NC-4.0**, matching the base model — the assistant turns are Tiny Aya "
        "Global generations, so they carry the same terms.")

for repo in ("tiny-aya-refusal-consistency-prompts", "tiny-aya-refusal-consistency-sft",
             "tiny-aya-refusal-consistency-eval"):
    p = hf_hub_download(f"{NS}/{repo}", "README.md", repo_type="dataset")
    t = Path(p).read_text()
    t2 = re.sub(r"^license:.*$", "license: cc-by-nc-4.0", t, count=1, flags=re.M)
    if "matching the base model" not in t2:
        t2 = t2.rstrip() + "\n\n## Licence\n\n" + NOTE + "\n"
    api.upload_file(path_or_fileobj=t2.encode(), path_in_repo="README.md",
                    repo_id=f"{NS}/{repo}", repo_type="dataset",
                    commit_message="licence: align with the base model (CC-BY-NC-4.0)")

# held-out generations
for name in ("heldout_base", "heldout_v4"):
    api.upload_file(path_or_fileobj=open(f"/Volumes/Drive/lexsi/data/{name}.jsonl", "rb").read(),
                    path_in_repo=f"heldout/{name}.jsonl",
                    repo_id=f"{NS}/tiny-aya-refusal-consistency-eval", repo_type="dataset",
                    commit_message="add held-out run (30 prompts written after training)")

files = api.list_repo_files(f"{NS}/tiny-aya-refusal-consistency-eval", repo_type="dataset")
print("eval repo files:")
for f in sorted(files):
    print(" ", f)
